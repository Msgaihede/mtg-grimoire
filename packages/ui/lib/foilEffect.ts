/**
 * **Which foil a copy is drawn as, and where the light falls on it.**
 *
 * `FoilOverlay` (`components/CardArt.tsx`) used to lay one holo gradient over every foil, so a
 * Surge Foil, a Ripple Foil and an etched copy looked the same as any other foil — the owner's
 * report on 2026-11-15, "they look like any other foil". Scryfall cannot help: it
 * keeps **one picture per printing**, so a printing sold plain *and* special (693 surge, 369
 * silver, 316 ripple and 326 etched printings in the 2026-11 corpus) is photographed plain, and
 * the kind of foil lives only in `promo_types`. So the app draws the kind itself, and this module
 * names which kind a copy gets.
 *
 * **Where an effect is drawn did not change** (the owner's call, 2026-11-15): wherever the app
 * already drew the old sheen — a copy whose finish is known to be foil or etched (a collection
 * row, a deck card, a wish, the card pane's chosen finish), and on a printing-shaped wall only a
 * printing sold in that finish alone (`soleFinish`). This module never widens that; it only says
 * what the sheen looks like once a caller has decided there is one.
 *
 * Each kind was tuned on a design canvas against photographs of real cards, kind by kind, and the
 * CSS that draws them is the "Foil" section of `index.css`; the patterns they mask with are
 * generated by `scripts/foil-textures.ts`.
 */
import type { Finish } from "./finish";
import type { Treatment } from "./treatment";

/**
 * The drawings the app has. `foil` is traditional foil and the fallback for every named foil
 * without a drawing of its own (First Place, Step-and-Compleat, Oil Slick and the rest — 582
 * printings between them in the 2026-11 corpus, not one of them also sold plain, so Scryfall's
 * picture of each is already the foil card).
 */
export const FOIL_EFFECTS = [
  "foil",
  "etched",
  "surge",
  "silver",
  "ripple",
  "mana",
  "galaxy",
  "rainbow",
  "doublerainbow",
  "halo",
  "textured",
  "confetti",
  "fracture",
] as const;
export type FoilEffect = (typeof FOIL_EFFECTS)[number];

/** The `promo_types` member (`Treatment.id`) each drawing answers to. */
const BY_TREATMENT: Readonly<Record<string, FoilEffect>> = {
  surgefoil: "surge",
  silverfoil: "silver",
  ripplefoil: "ripple",
  // Foundations' mana foil (FDN 362–421, every one foil-only): drawn as itself since issue #1689,
  // where it had been drawn as traditional foil.
  manafoil: "mana",
  galaxyfoil: "galaxy",
  rainbowfoil: "rainbow",
  doublerainbow: "doublerainbow",
  halofoil: "halo",
  textured: "textured",
  confettifoil: "confetti",
  fracturefoil: "fracture",
};

/**
 * The drawing for a copy in `finish` carrying `treatments` (`finishTreatments`' answer), or `null`
 * for a copy that draws no foil at all.
 *
 * - `nonfoil` and `null` draw nothing, the same rule `FoilOverlay` has always had.
 * - `etched` is etched whatever else the printing is called: etched is a finish, and its look —
 *   a frosted metal frame — is a property of the process rather than of a promo.
 * - `foil` is the first treatment with a drawing, in `CARD_TREATMENTS` order, else traditional.
 */
export function foilEffect(
  finish: Finish | null,
  treatments: readonly Treatment[] = [],
): FoilEffect | null {
  if (finish === "etched") return "etched";
  if (finish !== "foil") return null;
  for (const t of treatments) {
    const drawn = BY_TREATMENT[t.id];
    if (drawn) return drawn;
  }
  return "foil";
}

/**
 * How many pattern layers each drawing paints over the base sheen and under the glare. The overlay
 * mounts exactly these (`foil-pattern`, `foil-pattern-2`, `foil-pattern-3`), so a traditional foil
 * on a wall of hundreds costs two spans and not five.
 */
export const FOIL_PATTERN_LAYERS: Readonly<Record<FoilEffect, 0 | 1 | 2 | 3>> = {
  foil: 0,
  rainbow: 0,
  doublerainbow: 0,
  halo: 0,
  etched: 2,
  surge: 2,
  silver: 2,
  mana: 2,
  galaxy: 2,
  // Nine rings in one layer of gradients (issue #1689); it was three pictures in three layers.
  ripple: 1,
  textured: 1,
  confetti: 1,
  fracture: 1,
};

/**
 * **How strong every drawing is: `--foil-on`.** 0.6 since issue #1689 ("all foils are too blown
 * out"), the strength the owner approved on the design canvas; it was 1. Every layer in
 * `index.css` scales by it, and traditional foil divides it back out (`/ 0.6`) because that drawing
 * is the pre-2026-11-15 sheen at its own alphas, which were never blown out.
 */
export const FOIL_STRENGTH = 0.6;

/**
 * Where a card's light rests while the pointer is outside the window, under a finger and for a
 * reader who asked for less motion: upper left, the angle a card on a desk is usually seen at.
 * Each card rests a little off it ({@link FoilCard}).
 */
export const FOIL_REST = { x: 0.32, y: 0.28 } as const;

/** The sweep's direction when nothing turns it: the pre-2026-11-15 sheen's 115°. */
export const FOIL_ANGLE = 115;

/**
 * **What makes one card's foil different from its neighbour's** — the owner, on the design canvas
 * (2026-11-15): "all the foil sheens go in the same direction, and move at the same rate… across a
 * whole card wall". A card's sweep turns up to 9° either side of {@link FOIL_ANGLE}, and its light
 * rests up to 0.08 of the card away from {@link FOIL_REST} on each axis.
 */
export interface FoilCard {
  /** The sweep's direction, in degrees. */
  angle: number;
  /** The resting light's offset from {@link FOIL_REST}, in card widths and heights. */
  ox: number;
  oy: number;
}

/**
 * A card's constants from a seed — its card id, so the same card is the same foil on every wall
 * and after every scroll. FNV-1a over the seed, then three draws of a 32-bit LCG.
 */
export function foilCard(seed: string): FoilCard {
  let h = 0x811c9dc5;
  for (let i = 0; i < seed.length; i++) h = Math.imul(h ^ seed.charCodeAt(i), 0x01000193) >>> 0;
  const draw = () => (h = (Math.imul(h, 1664525) + 1013904223) >>> 0) / 4294967296;
  return {
    angle: FOIL_ANGLE + (draw() - 0.5) * 18,
    ox: (draw() - 0.5) * 0.16,
    oy: (draw() - 0.5) * 0.16,
  };
}

/**
 * How far the pointer's place on the card it is on moves that card's light: 0.9 of the card,
 * mirrored. **Only that card's light moves** — the owner's call on 2026-11-18, from readers'
 * feedback: a card the pointer is not on keeps its resting light. (It drifted a fifth of itself as
 * the pointer crossed the window from 2026-11-16, and followed the pointer before that.)
 */
export const FOIL_HOVER = 0.9;

/** What the pointer gives one card, all 0..1. */
export interface FoilPointer {
  /** The pointer's place on this card; the middle when it is not on it. */
  rx: number;
  ry: number;
  /**
   * How much this card is the one under the pointer: 0 off it, rising to 1 across the outer 15 %
   * of its edge, so a pointer arriving on a card does not snap its light across.
   */
  hover: number;
}

const smoothstep = (a: number, b: number, x: number): number => {
  const t = Math.min(1, Math.max(0, (x - a) / (b - a)));
  return t * t * (3 - 2 * t);
};

/**
 * What a pointer at `at` gives a card drawn in `box`. `onCard` is whether this card is the one the
 * pointer is on — the topmost under it, which the caller knows from the pointer event's target. A
 * box alone cannot say: in the deck's stacks the pointer is inside nine cards' boxes at once and
 * only one of them shows there.
 */
export function foilPointer(
  at: { x: number; y: number },
  box: { left: number; top: number; width: number; height: number },
  onCard: boolean,
): FoilPointer {
  const rx = (at.x - box.left) / Math.max(1, box.width);
  const ry = (at.y - box.top) / Math.max(1, box.height);
  const inside = onCard && rx >= 0 && rx <= 1 && ry >= 0 && ry <= 1;
  if (!inside) return { rx: 0.5, ry: 0.5, hover: 0 };
  const edge = Math.min(rx, 1 - rx, ry, 1 - ry);
  return { rx, ry, hover: smoothstep(0, 0.15, edge) };
}

const clamp01 = (v: number) => Math.min(1, Math.max(0, v));

/**
 * Where on `card` the light is, for what the pointer gives it — `null` for no pointer at all
 * (outside the window, a finger, less motion), which is the card's resting light, as is a card the
 * pointer is not on.
 *
 * The card the pointer is on moves {@link FOIL_HOVER} of itself across itself, mirrored, blended in
 * from its rest by `hover`. **No easing in time** — the owner's call ("remove the smooth
 * interpolation too"): the light is wherever the pointer puts it, at once.
 */
export function foilAim(given: FoilPointer | null, card: FoilCard): { x: number; y: number } {
  const restX = FOIL_REST.x + card.ox;
  const restY = FOIL_REST.y + card.oy;
  if (given === null || given.hover === 0) return { x: restX, y: restY };
  const onX = 0.5 + FOIL_HOVER * (0.5 - given.rx);
  const onY = 0.5 + FOIL_HOVER * (0.5 - given.ry);
  return {
    x: clamp01(restX + given.hover * (onX - restX)),
    y: clamp01(restY + given.hover * (onY - restY)),
  };
}

/**
 * Ripple's nine rings, in card space: centre `x` across and `y` down (0..1, a few just off the
 * card), radius in card widths, and the direction (degrees) the light moves to grow it. They never
 * move — issue #1689 asked for "about half as many circles, which grow/shrink and gradually fade
 * instead of moving"; the owner then settled on nine with five showing.
 */
export const RIPPLE_RINGS: readonly (readonly [number, number, number, number])[] = [
  [0.2, 0.14, 0.3, 30],
  [0.8, 0.2, 0.26, 150],
  [0.46, 0.4, 0.22, 270],
  [0.08, 0.55, 0.32, 80],
  [0.9, 0.6, 0.34, 210],
  [0.52, 0.76, 0.28, 330],
  [0.2, 0.95, 0.24, 120],
  [0.8, 1.0, 0.22, 0],
  [0.52, 0.06, 0.2, 240],
];

/** How many of the rings show at once: the ones nearest the light. */
export const RIPPLE_SHOWN = 5;

/**
 * Each ring's size and visibility for a light at `(x, y)`. A ring's spot is its centre pulled
 * into the range the light travels; the {@link RIPPLE_SHOWN} spots nearest the light show, and the
 * line between the fifth and the sixth fades over 0.1 either side, so a ring dissolves rather than
 * blinks (the fade itself takes 0.9 s, in `index.css`). A ring grows as the light crosses it the
 * way it faces.
 */
export function rippleRings(x: number, y: number): { grow: number; show: number }[] {
  const spots = RIPPLE_RINGS.map(([cx, cy]) => [0.15 + 0.7 * cx, 0.15 + 0.7 * Math.min(1, cy)]);
  const d = spots.map(([sx, sy]) => Math.hypot(x - sx, y - sy));
  const sorted = [...d].sort((a, b) => a - b);
  const cut = (sorted[RIPPLE_SHOWN - 1] + sorted[RIPPLE_SHOWN]) / 2;
  return RIPPLE_RINGS.map(([, , , dir], i) => {
    const a = (dir * Math.PI) / 180;
    const along = (x - spots[i][0]) * Math.cos(a) + (y - spots[i][1]) * Math.sin(a);
    return {
      grow: 0.7 + 0.6 * smoothstep(-0.35, 0.35, along),
      show: 1 - smoothstep(cut - 0.1, cut + 0.1, d[i]),
    };
  });
}

/**
 * The CSS custom properties that place the light at `at` (0..1 each) on `card`.
 *
 * Every layer of every drawing reads only these, so the card itself never moves — no tilt, the
 * owner's call. `--foil-angle` turns the card's sweep and `--foil-at` is where along it the bright
 * band sits: the light's position projected onto the sweep, so the band crosses the card as the
 * light does.
 *
 * `ripple` adds the nine rings' `--foil-gN` (size) and `--foil-sN` (shown). Only the card under the
 * pointer moves its light, so only it fades rings in and out: a deck of ripples is not a hundred
 * 0.9 s fades repainting every frame.
 */
export function foilLight(
  at: { x: number; y: number },
  card: FoilCard,
  ripple = false,
): Record<string, string> {
  const t = (card.angle * Math.PI) / 180;
  const along = (at.x - 0.5) * Math.sin(t) - (at.y - 0.5) * Math.cos(t);
  const vars: Record<string, string> = {
    "--foil-px": at.x.toFixed(3),
    "--foil-py": at.y.toFixed(3),
    "--foil-mx": `${(at.x * 100).toFixed(1)}%`,
    "--foil-my": `${(at.y * 100).toFixed(1)}%`,
    "--foil-on": String(FOIL_STRENGTH),
    "--foil-angle": `${card.angle.toFixed(1)}deg`,
    "--foil-at": `${(50 + 45 * along).toFixed(1)}%`,
  };
  if (!ripple) return vars;
  rippleRings(at.x, at.y).forEach(({ grow, show }, i) => {
    vars[`--foil-g${i + 1}`] = grow.toFixed(2);
    // In twentieths: a ring's visibility changes, and so repaints, only when it visibly moves.
    vars[`--foil-s${i + 1}`] = (Math.round(show * 20) / 20).toFixed(2);
  });
  return vars;
}
