/**
 * **Which foil a copy is drawn as, and where the light falls on it.**
 *
 * `FoilOverlay` (`components/CardArt.tsx`) used to lay one holo gradient over every foil, so a
 * Surge Foil, a Ripple Foil and an etched copy looked the same as any other foil — the owner's
 * report on 2026-11-15, "they look like any other foil". Scryfall cannot help: it
 * keeps **one picture per printing**, so a printing sold plain *and* special (693 surge, 369
 * silver, 316 ripple and 326 etched printings in the 2026-11 corpus) is photographed plain, and
 * the kind of foil lives only in `promo_types`. So the app draws the kind itself, and this module
 * names which kind a copy gets.
 *
 * **Where an effect is drawn did not change** (the owner's call, 2026-11-15): wherever the app
 * already drew the old sheen — a copy whose finish is known to be foil or etched (a collection
 * row, a deck card, a wish, the card pane's chosen finish), and on a printing-shaped wall only a
 * printing sold in that finish alone (`soleFinish`). This module never widens that; it only says
 * what the sheen looks like once a caller has decided there is one.
 *
 * Each kind was tuned on a design canvas against photographs of real cards, kind by kind, and the
 * CSS that draws them is the "Foil" section of `index.css`; the patterns they mask with are
 * generated by `scripts/foil-textures.ts`.
 */
import type { Finish } from "./finish";
import type { Treatment } from "./treatment";

/**
 * The drawings the app has. `foil` is traditional foil and the fallback for every named foil
 * without a drawing of its own (First Place, Step-and-Compleat, Oil Slick and the rest — 582
 * printings between them in the 2026-11 corpus, not one of them also sold plain, so Scryfall's
 * picture of each is already the foil card).
 */
export const FOIL_EFFECTS = [
  "foil",
  "etched",
  "surge",
  "silver",
  "ripple",
  "galaxy",
  "rainbow",
  "doublerainbow",
  "halo",
  "textured",
  "confetti",
  "fracture",
] as const;
export type FoilEffect = (typeof FOIL_EFFECTS)[number];

/** The `promo_types` member (`Treatment.id`) each drawing answers to. */
const BY_TREATMENT: Readonly<Record<string, FoilEffect>> = {
  surgefoil: "surge",
  silverfoil: "silver",
  ripplefoil: "ripple",
  galaxyfoil: "galaxy",
  rainbowfoil: "rainbow",
  doublerainbow: "doublerainbow",
  halofoil: "halo",
  textured: "textured",
  confettifoil: "confetti",
  fracturefoil: "fracture",
};

/**
 * The drawing for a copy in `finish` carrying `treatments` (`finishTreatments`' answer), or `null`
 * for a copy that draws no foil at all.
 *
 * - `nonfoil` and `null` draw nothing, the same rule `FoilOverlay` has always had.
 * - `etched` is etched whatever else the printing is called: etched is a finish, and its look —
 *   a frosted metal frame — is a property of the process rather than of a promo.
 * - `foil` is the first treatment with a drawing, in `CARD_TREATMENTS` order, else traditional.
 */
export function foilEffect(
  finish: Finish | null,
  treatments: readonly Treatment[] = [],
): FoilEffect | null {
  if (finish === "etched") return "etched";
  if (finish !== "foil") return null;
  for (const t of treatments) {
    const drawn = BY_TREATMENT[t.id];
    if (drawn) return drawn;
  }
  return "foil";
}

/**
 * How many pattern layers each drawing paints over the base sheen and under the glare. The overlay
 * mounts exactly these (`foil-pattern`, `foil-pattern-2`, `foil-pattern-3`), so a traditional foil
 * on a wall of hundreds costs two spans and not five.
 */
export const FOIL_PATTERN_LAYERS: Readonly<Record<FoilEffect, 0 | 1 | 2 | 3>> = {
  foil: 0,
  rainbow: 0,
  doublerainbow: 0,
  halo: 0,
  etched: 2,
  surge: 2,
  silver: 2,
  galaxy: 2,
  ripple: 3,
  textured: 1,
  confetti: 1,
  fracture: 1,
};

/**
 * Where the light rests when no pointer is over the card: upper left, the angle a card on a desk
 * is usually seen at. Every tile on a wall shows this, so the wall is still and every foil still
 * reads as foil.
 */
export const FOIL_REST = { x: 0.32, y: 0.28 } as const;

/**
 * Ripple's three circle sets, each strongest when the light is near its own spot — the owner asked
 * for circles that "fade and fade in new circles in different locations… like a camera obscura".
 * Points on the card, 0..1.
 */
const RIPPLE_ANCHORS: readonly (readonly [number, number])[] = [
  [0.22, 0.25],
  [0.8, 0.4],
  [0.4, 0.85],
];

/** A set's weight: a floor so no set ever vanishes outright, plus a Gaussian bump at its anchor. */
function anchorWeight(x: number, y: number, [ax, ay]: readonly [number, number]): number {
  return 0.12 + 0.88 * Math.exp(-((x - ax) ** 2 + (y - ay) ** 2) / (2 * 0.28 * 0.28));
}

/**
 * The CSS custom properties that place the light, for a light at `(x, y)` on the card (0..1 each)
 * that is either `lit` (a pointer is over the card) or resting.
 *
 * Every layer of every drawing reads only these, so the card itself never moves — no tilt, the
 * owner's call — while the sheen, the glare and the patterns follow the pointer.
 */
export function foilLight(x: number, y: number, lit: boolean): Record<string, string> {
  const [wa, wb, wc] = RIPPLE_ANCHORS.map((a) => anchorWeight(x, y, a));
  return {
    "--foil-px": x.toFixed(3),
    "--foil-py": y.toFixed(3),
    "--foil-mx": `${(x * 100).toFixed(1)}%`,
    "--foil-my": `${(y * 100).toFixed(1)}%`,
    "--foil-hyp": Math.min(1, Math.hypot(x - 0.5, y - 0.5) * 2).toFixed(3),
    "--foil-on": lit ? "1" : "0.55",
    "--foil-wa": wa.toFixed(3),
    "--foil-wb": wb.toFixed(3),
    "--foil-wc": wc.toFixed(3),
  };
}
